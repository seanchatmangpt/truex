import type { Database } from 'better-sqlite3';
import { DeltaJournal } from './journal.js';
import { SQLiteReceiptStore } from './receipt-store.js';
import { SnapshotManager, type StateSnapshot } from './snapshot.js';
import { ProductionLine } from '../manufacturing/line.js';
import type { GraphDelta, Receipt, Quad } from '../runtime-law.js';
import type { TruexContext } from '../context.js';

/**
 * S3PersistenceMembrane defines the contract for persisting TrueX state 
 * to an object storage layer like Amazon S3.
 * 
 * Gall Law S3: A simple working system that provides durability and 
 * traceability for the quad-graph state.
 */
export interface S3PersistenceMembrane {
  putSnapshot(receiptHash: string, snapshot: StateSnapshot): Promise<void>;
  getSnapshot(receiptHash: string): Promise<StateSnapshot | null>;
  putReceipt(receipt: Receipt): Promise<void>;
  getReceipt(receiptHash: string): Promise<Receipt | null>;
  listReceipts(): Promise<string[]>;
}

/**
 * PersistenceOrchestrator: The primary control unit for the TrueX persistence lifecycle.
 * 
 * It coordinates the flow: Execute -> Receipt -> Persist -> Crash -> Cold-Load -> Replay -> Converge.
 * 
 * Jidoka (TPS): Ensures that every step is verified, and the system can 
 * recover to a consistent state ('Converge') even after a total crash.
 */
export class PersistenceOrchestrator {
  private readonly journal: DeltaJournal;
  private readonly receiptStore: SQLiteReceiptStore;
  private currentState: Quad[] = [];

  constructor(
    private readonly db: Database,
    private readonly productionLine: ProductionLine,
    private readonly s3Membrane: S3PersistenceMembrane
  ) {
    this.journal = new DeltaJournal(db);
    this.receiptStore = new SQLiteReceiptStore(db);
  }

  /**
   * Executes a delta and ensures it is persisted both locally (WAL) and remotely (S3).
   * 
   * @param ctx Execution context.
   * @param delta The delta to process.
   * @returns The receipts generated by the execution.
   */
  async execute(ctx: TruexContext, delta: GraphDelta): Promise<Receipt[]> {
    // 1. Journal Delta (BEFORE execution) - Zero-Loss Cold-Load requirement
    const journalIdx = this.journal.append(delta);

    // 2. Execute via Production Line
    const results = this.productionLine.manufacture(delta);
    const receipts = results.map(r => r.receipt);

    // Update current state based on replayed delta
    this.currentState = SnapshotManager.applyDelta(this.currentState, delta);

    // 3. Update local state and remote persistence
    for (const res of results) {
      const receipt = res.receipt;
      this.receiptStore.append(receipt);
      await this.s3Membrane.putReceipt(receipt);
      
      // Update current state based on hook effects
      const emittedQuads = res.effects
          .filter(e => e.kind === 'add-quad')
          .map(e => (e as any).quad as Quad);
            
      this.currentState = SnapshotManager.applyDelta(this.currentState, { id: delta.id, adds: emittedQuads, deletes: [] });

      // We also persist a snapshot for every confirmed receipt to ensure cold-load efficiency
      if (receipt.status === 'confirmed') {
        const snapshot = SnapshotManager.create(this.currentState, receipt.receiptHash); 
        await this.s3Membrane.putSnapshot(receipt.receiptHash, snapshot);
      }
    }

    // 4. Mark as applied locally
    this.journal.markApplied(journalIdx);

    return receipts;
  }

  /**
   * Recovers the system state from a crash.
   * 
   * Lifecycle: Cold-Load -> Replay -> Converge.
   */
  async recover(): Promise<{ state: Quad[]; replayed: number }> {
    // 1. Cold-Load: Find the latest receipt and load its state from S3
    const latestReceipt = this.receiptStore.latest();
    let currentState: Quad[] = [];
    let startFromJournalIdx = 0;

    if (latestReceipt) {
      const snapshot = await this.s3Membrane.getSnapshot(latestReceipt.receiptHash);
      if (snapshot) {
        currentState = snapshot.quads;
        // In a real system, we'd find the journal index corresponding to this snapshot
      }
    }

    // 2. Replay: Find deltas that were journaled (The WAL)
    // We replay EVERYTHING from the start if we have no snapshot, or everything unapplied.
    let replayed = 0;
    const deltasToReplay = latestReceipt ? this.journal.getUnapplied() : this.journal.replay(0);
    
    for (const { idx, delta } of deltasToReplay) {
      const results = this.productionLine.manufacture(delta);
      
      // Update current state based on replayed delta
      currentState = SnapshotManager.applyDelta(currentState, delta);

      for (const res of results) {
        // Durability: Re-persist recovered receipts
        this.receiptStore.append(res.receipt);
        await this.s3Membrane.putReceipt(res.receipt);
        
        // Update current state based on hook effects
        const emittedQuads = res.effects
            .filter(e => e.kind === 'add-quad')
            .map(e => (e as any).quad as Quad);
            
        currentState = SnapshotManager.applyDelta(currentState, { id: delta.id, adds: emittedQuads, deletes: [] });
      }
      
      // Successfully replayed, mark as applied
      this.journal.markApplied(idx);
      replayed++;
    }

    // 3. Converge: The final currentState is now synchronized and consistent
    this.currentState = currentState;
    return { state: currentState, replayed };
  }

  /**
   * Returns the local journal instance.
   */
  getJournal(): DeltaJournal {
    return this.journal;
  }

  /**
   * Returns the local receipt store instance.
   */
  getReceiptStore(): SQLiteReceiptStore {
    return this.receiptStore;
  }
}
