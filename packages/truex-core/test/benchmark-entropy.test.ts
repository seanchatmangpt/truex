import { describe, it, expect } from 'vitest';
import { generateChurchDeltas, generateChurchHooks } from '../src/benchmark/million-hook-church';
import { hash } from '../src/hash';

describe('Benchmark Entropy & Determinism', () => {
  const seed = 12345;

  it('should generate identical deltas for the same seed', () => {
    const deltas1 = generateChurchDeltas(seed, 100);
    const deltas2 = generateChurchDeltas(seed, 100);
    expect(deltas1).toEqual(deltas2);
    expect(hash(deltas1)).toBe(hash(deltas2));
  });

  it('should generate different deltas for different seeds', () => {
    const deltas1 = generateChurchDeltas(seed, 100);
    const deltas2 = generateChurchDeltas(seed + 1, 100);
    expect(deltas1).not.toEqual(deltas2);
    expect(hash(deltas1)).not.toBe(hash(deltas2));
  });

  it('should generate identical hooks for the same seed', () => {
    const hooks1 = generateChurchHooks(seed, 50);
    const hooks2 = generateChurchHooks(seed, 50);
    expect(hooks1).toEqual(hooks2);
    expect(hash(hooks1)).toBe(hash(hooks2));
  });

  it('should handle all required entity types deterministically', () => {
    const count = 1000;
    const deltas = generateChurchDeltas(seed, count);
    
    const typesSeen = new Set<string>();
    deltas.forEach(d => {
      const typeMatch = d.id.match(/delta-church-(.*)-\d+/);
      if (typeMatch) typesSeen.add(typeMatch[1]);
    });

    const expectedTypes = ['member', 'volunteer', 'room', 'event', 'care_request', 'notification', 'follow_up'];
    expectedTypes.forEach(type => {
      expect(typesSeen).toContain(type);
    });
  });

  it('should not contain any non-deterministic values like Date.now() or randomUUID()', () => {
    const deltas = generateChurchDeltas(seed, 100);
    const json = JSON.stringify(deltas);
    
    // UUIDs generated by our deterministic context follow a pattern if we use them,
    // but here we are using simple string IDs like `member:${i}`.
    // Let's just ensure no actual random-looking strings are there if not intended.
    // The current implementation uses:
    // const deltaId = `delta-church-${type}-${i}`;
    // const id = `${type}:${i}`; (mostly)
    
    expect(json).not.toMatch(/[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}/i);
  });
});
