/**
 * @module docs-link
 * @description
 * Gall Classification: Observatory Integration
 * Purpose: Links observatory outputs and generates the main dashboard README.
 * Ensures the aggregated facts are easily accessible.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { FactEmitter, EmitterMetadata } from './fact-emitter.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ROOT_DIR = path.resolve(__dirname, '../../../');
const DOCS_DIR = path.join(ROOT_DIR, 'docs/v1/latest');
const README_PATH = 'docs/v1/latest/README.md';

const FACTS_DIR = path.join(DOCS_DIR, 'facts');
const DIAGRAMS_DIR = path.join(DOCS_DIR, 'diagrams');
const RECEIPTS_DIR = path.join(DOCS_DIR, 'receipts');

/**
 * Emitter responsible for aggregating all fact records into a Markdown dashboard.
 */
export class DocsLinkEmitter extends FactEmitter {
  getMetadata(): EmitterMetadata {
    return {
      name: 'Docs Link Emitter',
      description: 'Links observatory outputs and generates the main dashboard README',
      outputPath: README_PATH
    };
  }

  protected collectFacts() {
    const timestamp = new Date().toISOString();
    
    let markdown = `# 🔭 Truex Observatory Dashboard\n\n`;
    markdown += `*Last Updated: ${timestamp}*\n\n`;
    
    markdown += `## 🏥 System Health\n\n`;
    
    const diagnosticsPath = path.join(FACTS_DIR, 'diagnostics.json');
    if (fs.existsSync(diagnosticsPath)) {
      const diagnostics = JSON.parse(fs.readFileSync(diagnosticsPath, 'utf8'));
      const status = diagnostics.health_check.status === 'healthy' ? '✅ Healthy' : '❌ Unhealthy';
      markdown += `**Status:** ${status}\n\n`;
      
      if (diagnostics.coverage) {
        const cov = diagnostics.coverage;
        if (cov.lines) {
          markdown += `**Test Coverage:** ${cov.lines.pct}% (Lines), ${cov.functions.pct}% (Functions)\n\n`;
        } else if (cov.message) {
          markdown += `**Test Coverage:** ${cov.message}\n\n`;
        }
      }
    } else {
      markdown += `**Status:** ⚠️ Diagnostics not found. Run \`npm run observatory\` to generate.\n\n`;
    }

    markdown += `## 🧩 Core Facts\n\n`;
    const coreFactsPath = path.join(FACTS_DIR, 'core-primitives.json');
    if (fs.existsSync(coreFactsPath)) {
      const coreFacts = JSON.parse(fs.readFileSync(coreFactsPath, 'utf8'));
      markdown += `- [Core Primitives](./facts/core-primitives.json)\n`;
      markdown += `  - Total Files: ${coreFacts.stats.totalFiles}\n`;
      markdown += `  - Total Symbols: ${coreFacts.stats.totalExportedSymbols}\n`;
    }

    markdown += `\n## 🏗️ Manufacturing & Integration\n\n`;
    const manufacturingPath = path.join(FACTS_DIR, 'manufacturing.json');
    if (fs.existsSync(manufacturingPath)) {
      markdown += `- [Manufacturing Facts](./facts/manufacturing.json)\n`;
    }
    const agyPath = path.join(FACTS_DIR, 'agy-integration.json');
    if (fs.existsSync(agyPath)) {
      markdown += `- [AGY Integration](./facts/agy-integration.json)\n`;
    }

    markdown += `\n## 💾 Persistence & Architecture\n\n`;
    const persistencePath = path.join(FACTS_DIR, 'persistence.json');
    if (fs.existsSync(persistencePath)) {
      markdown += `- [Persistence Facts](./facts/persistence.json)\n`;
    }
    
    markdown += `\n### 📊 Diagrams\n\n`;
    if (fs.existsSync(DIAGRAMS_DIR)) {
      const diagrams = fs.readdirSync(DIAGRAMS_DIR).filter(f => f.endsWith('.mmd'));
      for (const d of diagrams) {
        const name = d.replace(/-/g, ' ').replace('.mmd', '');
        const capitalized = name.charAt(0).toUpperCase() + name.slice(1);
        markdown += `- [${capitalized}](./diagrams/${d})\n`;
      }
    }

    markdown += `\n## 📜 Receipts\n\n`;
    if (fs.existsSync(RECEIPTS_DIR)) {
      const receipts = fs.readdirSync(RECEIPTS_DIR).filter(f => f.endsWith('.json'));
      for (const r of receipts) {
        markdown += `- [${r}](./receipts/${r})\n`;
      }
    }

    markdown += `\n---\n*Generated by Truex Observatory Linker*`;

    return markdown;
  }
}

/**
 * Generates the central documentation link/README file.
 * @returns A promise resolving to the markdown content.
 */
export async function generateDocsLink() {
  const emitter = new DocsLinkEmitter();
  return emitter.emit();
}

// Self-execute if run as a script
const isMain = process.argv[1] && (
  process.argv[1].endsWith('docs-link.ts') || 
  process.argv[1].endsWith('docs-link.js') ||
  process.argv[1] === fileURLToPath(import.meta.url)
);

if (isMain) {
  generateDocsLink();
}
